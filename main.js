const sectionLinks = [...document.querySelectorAll("[data-section-link]")];
const sections = [...document.querySelectorAll("[data-section]")];
const languageButtons = [...document.querySelectorAll("[data-lang]")];
const resumeDownloads = [...document.querySelectorAll("[data-resume-download]")];
const panelsContainer = document.querySelector(".panels");
const profileContent = document.querySelector(".content");
const contentNavigation = document.querySelector(".content__nav");
const desktopLayout = window.matchMedia("(min-width: 1040px)");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
let heroBoundary = profileContent?.offsetTop || 0;

function setLanguage(language, persist = true) {
  const lang = copy[language] ? language : "en";
  const dictionary = copy[lang];

  document.documentElement.lang = lang === "pt" ? "pt-PT" : "en";
  document.title = dictionary.documentTitle;
  document.querySelector('meta[name="description"]').setAttribute("content", dictionary.documentDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAlt];
    if (value) element.setAttribute("alt", value);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const value = dictionary[element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value);
  });

  languageButtons.forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
  });

  if (persist) localStorage.setItem("profile-language", lang);
  updateHeroSnapScope();
  requestSectionSync();
}

function syncHeroSnapScope() {
  const atHeroBoundary = !desktopLayout.matches && window.scrollY <= heroBoundary + 2;
  document.documentElement.classList.toggle("hero-snap", atHeroBoundary);
}

function updateHeroSnapScope() {
  heroBoundary = profileContent?.offsetTop || 0;
  syncHeroSnapScope();
}

let downloadStatusTimer = null;

function showDownloadStatus(message, isError = false) {
  let status = document.querySelector(".download-status");
  if (!status) {
    status = document.createElement("div");
    status.className = "download-status";
    status.setAttribute("role", "status");
    status.setAttribute("aria-live", "polite");
    document.body.append(status);
  }

  window.clearTimeout(downloadStatusTimer);
  status.textContent = message;
  status.classList.toggle("download-status--error", isError);
  status.classList.add("is-visible");
  downloadStatusTimer = window.setTimeout(() => status.classList.remove("is-visible"), 3200);
}

async function forceResumeDownload(event) {
  event.preventDefault();
  const link = event.currentTarget;
  if (link.getAttribute("aria-busy") === "true") return;

  const dictionary = document.documentElement.lang.startsWith("pt") ? copy.pt : copy.en;
  link.setAttribute("aria-busy", "true");
  showDownloadStatus(dictionary.downloadPreparing);

  try {
    const response = await fetch(link.href, { cache: "no-store", credentials: "same-origin" });
    if (!response.ok) throw new Error(`CV download failed with status ${response.status}`);

    const file = new Blob([await response.arrayBuffer()], { type: "application/pdf" });
    const objectUrl = URL.createObjectURL(file);
    const trigger = document.createElement("a");
    trigger.href = objectUrl;
    trigger.download = link.getAttribute("download");
    trigger.hidden = true;
    document.body.append(trigger);
    trigger.click();
    trigger.remove();
    window.setTimeout(() => URL.revokeObjectURL(objectUrl), 30000);

    link.closest("details")?.removeAttribute("open");
    showDownloadStatus(dictionary.downloadReady);
  } catch {
    showDownloadStatus(dictionary.downloadError, true);
  } finally {
    link.removeAttribute("aria-busy");
  }
}

function setCurrentSection(name) {
  sectionLinks.forEach((link) => {
    if (link.dataset.sectionLink === name) {
      link.setAttribute("aria-current", "page");
    } else {
      link.removeAttribute("aria-current");
    }
  });
}

function scrollToSection(name, { updateHash = true, behavior } = {}) {
  const section = sections.find((candidate) => candidate.dataset.section === name) || sections[0];
  if (!section) return;

  section.scrollIntoView({
    behavior: behavior || (reducedMotion.matches ? "instant" : "smooth"),
    block: "start"
  });
  setCurrentSection(section.dataset.section);
  if (updateHash) history.replaceState(null, "", `#${section.dataset.section}`);
}

let sectionSyncFrame = null;

function syncCurrentSection() {
  sectionSyncFrame = null;
  if (!sections.length) return;

  const desktop = desktopLayout.matches && panelsContainer;
  const navigationBottom = contentNavigation?.getBoundingClientRect().bottom || 0;
  const referenceLine = desktop
    ? panelsContainer.getBoundingClientRect().top + Math.min(panelsContainer.clientHeight * 0.28, 180)
    : navigationBottom + Math.min(window.innerHeight * 0.18, 140);
  const reachedEnd = desktop
    ? panelsContainer.scrollTop + panelsContainer.clientHeight >= panelsContainer.scrollHeight - 4
    : window.scrollY + window.innerHeight >= document.documentElement.scrollHeight - 4;

  let currentSection = sections[0];
  sections.forEach((section) => {
    if (section.getBoundingClientRect().top <= referenceLine) currentSection = section;
  });
  if (reachedEnd) currentSection = sections[sections.length - 1];

  setCurrentSection(currentSection.dataset.section);
}

function requestSectionSync() {
  if (sectionSyncFrame !== null) return;
  sectionSyncFrame = window.requestAnimationFrame(syncCurrentSection);
}

sectionLinks.forEach((link) => {
  link.addEventListener("click", (event) => {
    event.preventDefault();
    scrollToSection(link.dataset.sectionLink);
  });
});

window.addEventListener("scroll", requestSectionSync, { passive: true });
window.addEventListener("scroll", syncHeroSnapScope, { passive: true });
panelsContainer?.addEventListener("scroll", requestSectionSync, { passive: true });
window.addEventListener("resize", requestSectionSync);
window.addEventListener("resize", updateHeroSnapScope);
desktopLayout.addEventListener("change", () => {
  updateHeroSnapScope();
  requestSectionSync();
});
window.addEventListener("hashchange", () => {
  const name = window.location.hash.slice(1).replace(/^panel-/, "");
  if (sections.some((section) => section.dataset.section === name)) {
    scrollToSection(name, { updateHash: false });
  }
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

resumeDownloads.forEach((link) => {
  link.addEventListener("click", forceResumeDownload);
});

document.addEventListener("click", (event) => {
  document.querySelectorAll(".resume-menu[open]").forEach((menu) => {
    if (!menu.contains(event.target)) menu.removeAttribute("open");
  });
});

